PLACE_BY_KEY = {p[0]: p for p in PLACES}
# 别名 -> 词典 key（供作者表/朝代兜底使用）
ALIAS = {
    '汴京': '开封', '大都': '北京', '临安': '临安', '荆州': '襄阳',
    '武夷山': '庐山', '永州': '洞庭', '金陵': '金陵', '长安': '长安',
}
def resolve_key(k):
    return ALIAS.get(k, k)


def match_place(text):
    """从文本中匹配地名，返回 (地名key, 具体名) —— 长关键词优先。"""
    hits = []
    for key, ancient, modern, lat, lng, kws in PLACES:
        for kw in kws:
            if kw in text:
                hits.append((len(kw), key, ancient))
                break
    if not hits:
        return None
    hits.sort(reverse=True)  # 关键词越长越具体
    return hits[0][1], hits[0][2]


def build_location(place_key, ancient_override=None, precision='approximate', source=''):
    place_key = resolve_key(place_key)
    if place_key not in PLACE_BY_KEY:
        place_key = '长安'
    key, ancient, modern, lat, lng, _ = PLACE_BY_KEY[place_key]
    return {
        'ancientName': ancient_override or ancient,
        'modernName': modern,
        'latitude': lat,
        'longitude': lng,
        'precision': precision,
        'source': source,
        'note': '地点按诗词文本线索/作者活动地推断，为地名附近约略位置，非精确写作坐标。',
    }


def main():
    poems = []
    for f in sorted(glob.glob(os.path.join(POEMS_DIR, '*.json'))):
        if os.path.basename(f) == 'locations.json':
            continue
        for p in json.load(open(f, encoding='utf-8')):
            poems.append(p)

    result = {}
    stats = collections.Counter()
    for p in poems:
        pid = p['id']
        # 1) 已有 location 优先
        if p.get('location') and p['location'].get('latitude'):
            result[pid] = p['location']
            stats['已有'] += 1
            continue

        text = ' '.join(str(p.get(k, '')) for k in ['title', 'background', 'notes', 'content', 'analysis'])
        # 2) 文本匹配地名
        hit = match_place(text)
        if hit:
            key, ancient = hit
            result[pid] = build_location(key, ancient, 'approximate', '诗词文本与背景中的地名线索')
            stats['文本地名'] += 1
            continue
        # 3) 作者籍贯/活动地
        author = p.get('author')
        if author in AUTHOR_PLACE:
            result[pid] = build_location(AUTHOR_PLACE[author], precision='inferred',
                                         source=f'作者{author}的籍贯/长期活动地')
            stats['作者籍贯'] += 1
            continue
        # 4) 朝代都城兜底
        cap = DYNASTY_CAPITAL.get(p.get('dynasty'))
        if cap and resolve_key(cap) in PLACE_BY_KEY:
            result[pid] = build_location(cap, precision='inferred',
                                         source=f'{p.get("dynasty")}代都城/文化中心（兜底）')
            stats['朝代兜底'] += 1
            continue
        stats['未覆盖'] += 1

    # 直接写回 5 个诗词 json 的 location 字段（数据层无需改动，全文生效）
    for f in sorted(glob.glob(os.path.join(POEMS_DIR, '*.json'))):
        base = os.path.basename(f)
        if base in ('locations.json',):
            continue
        data = json.load(open(f, encoding='utf-8'))
        changed = 0
        for p in data:
            loc = result.get(p['id'])
            if loc and p.get('location') != loc:
                p['location'] = loc
                changed += 1
        with open(f, 'w', encoding='utf-8') as fo:
            json.dump(data, fo, ensure_ascii=False, indent=2)
        print(f'  {base}: 写入 {changed}/{len(data)} 条 location')

    print('\n总计:', len(poems))
    for k, v in stats.items():
        print(f'  {k}: {v}')
    # 唯一地点数
    places = collections.Counter((v['ancientName'], v['modernName']) for v in result.values())
    print('唯一地点数:', len(places))
    print('点位TOP15:', places.most_common(15))


if __name__ == '__main__':
    main()
