def build(theme):
    return THEME.get(theme, DEFAULT)

records = []
used = set(existing_titles)
skipped = []
for i, (title, poet, dc, dn, form, lines, theme) in enumerate(P):
    if title in used:
        skipped.append(title)
        continue
    member = MEMBERS[i % 5]
    key = (dc, member)
    seq = next_seq.get(key, 1)
    next_seq[key] = seq + 1
    pid = f"{dc}-{member}-{seq:04d}"
    analysis, appreciation, concept = build(theme)
    records.append({
        "id": pid,
        "title": title,
        "author": poet,
        "dynasty": dn,
        "form": form,
        "content": lines,
        "translation": "",
        "notes": "",
        "background": "",
        "analysis": analysis,
        "appreciation": appreciation,
        "artisticConcept": concept,
        "tags": [theme, dn, form],
        "theme": theme,
    })
    used.add(title)

